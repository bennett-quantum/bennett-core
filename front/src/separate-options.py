#!/usr/bin/env python3
"""Writes SeparateOptions.def: the spellings of clang's driver options that take the arguments after them as their
values, from clang's include/clang/Driver/Options.td (the one of clang 18.1.3 for this tree; its sha256 is in the
.def's first lines).

The option records are read through LLVM 18's own llvm-tblgen (`-dump-json`, with LLVM's Option/OptParser.td from
`llvm-config-18 --includedir`), not by matching the .td text: the text defines options that a pattern does not see,
without a name (`def : Separate<["--"], "config">, Alias<config>;`), through classes (`CLJoinedOrSeparate<"o">`) and
by `Option<...>` with a kind constant, and it sets visibility in enclosing `let` blocks. A record is listed if its
kind is Separate, JoinedOrSeparate, JoinedAndSeparate or MultiArg, its prefix is `-` or `--`, and it is visible in
the driver's default mode (`DefaultVis`, the mode bennett-cc runs clang in): the list says how that mode reads the
user's command. An option of another mode is no option there: clang refuses it or reads its spelling as a different
option (measured with `clang -###`: `-Fo` and `-Tc` of clang-cl mode and cc1's `-objc-isystem` leave a following
`-O2` an option), so listing it would withhold that option from the baseline (BaselineOptions.h). `--`, the one
default-mode option that takes all the remaining arguments, is handled in BaselineOptions.cpp.
Run: separate-options.py Options.td > SeparateOptions.def
"""
import hashlib
import json
import subprocess
import sys

# The kinds that read arguments after the option's own, and how the option's spelling is matched: `Exact`, the
# argument is the spelling; `Prefix`, it starts with it (JoinedAndSeparate, `-Xarch_<arch> <value>`).
KINDS = {"KIND_SEPARATE": "Exact", "KIND_JOINED_OR_SEPARATE": "Exact", "KIND_JOINED_AND_SEPARATE": "Prefix",
         "KIND_MULTIARG": "Exact"}


def llvm(flag):
    return subprocess.run(["llvm-config-18", flag], check=True, capture_output=True, text=True).stdout.strip()


def main(path):
    data = open(path, "rb").read()
    include = llvm("--includedir")
    parser = open(include + "/llvm/Option/OptParser.td", "rb").read()
    dump = subprocess.run([llvm("--bindir") + "/llvm-tblgen", "-dump-json", "-I", include, path], check=True,
                          capture_output=True, text=True).stdout
    records = json.loads(dump)
    found = {}
    for name in records["!instanceof"]["Option"]:
        option = records[name]
        kind = option["Kind"]["def"]
        if kind not in KINDS or "DefaultVis" not in [v["def"] for v in option["Visibility"]]:
            continue
        values = option["NumArgs"] if kind == "KIND_MULTIARG" else 1
        for prefix in option["Prefixes"]:
            if prefix in ("-", "--"):
                found[prefix + option["Name"]] = (KINDS[kind], values)
    print("// Generated by separate-options.py from clang 18.1.3's include/clang/Driver/Options.td (sha256")
    print("// " + hashlib.sha256(data).hexdigest() + ") and LLVM 18.1.3's Option/OptParser.td (sha256")
    print("// " + hashlib.sha256(parser).hexdigest() + "): the options of the driver's default mode that")
    print("// take the next arguments as their values. BENNETT_SEPARATE(spelling, match, values): `Exact`, the")
    print("// argument is the spelling; `Prefix`, it starts with it (JoinedAndSeparate). `values` arguments follow it.")
    for spelling, (match, count) in sorted(found.items()):
        print(f'BENNETT_SEPARATE("{spelling}", {match}, {count})')


if __name__ == "__main__":
    main(sys.argv[1])
