#!/usr/bin/env python3
"""Writes SeparateOptions.def: the spellings of clang's driver options that take the arguments after them as their
values, read from clang's include/clang/Driver/Options.td (the one of clang 18.1.3 for this tree; its sha256 is in
the .def's first lines). Every `def` of kind Separate, JoinedOrSeparate, JoinedAndSeparate or MultiArg with the
prefix `-` or `--` is listed, whatever its visibility: listing an option clang does not accept in its plain mode
only withholds more from the baseline (BaselineOptions.h). Run: separate-options.py Options.td > SeparateOptions.def
"""
import hashlib
import re
import sys

KINDS = {"Separate": "Exact", "JoinedOrSeparate": "Exact", "JoinedAndSeparate": "Prefix", "MultiArg": "Exact"}
DEF = re.compile(r'def\s+\w+\s*:\s*(Separate|JoinedOrSeparate|JoinedAndSeparate|MultiArg)<\[([^\]]*)\],\s*"([^"]+)"'
                 r'(?:,\s*(\d+))?>')


def main(path):
    data = open(path, "rb").read()
    found = {}
    for match in DEF.finditer(data.decode()):
        kind, prefixes, name, count = match.groups()
        for prefix in re.findall(r'"([^"]*)"', prefixes):
            if prefix in ("-", "--"):
                found[prefix + name] = (KINDS[kind], int(count or 1))
    print("// Generated by separate-options.py from clang 18.1.3's include/clang/Driver/Options.td (sha256")
    print("// " + hashlib.sha256(data).hexdigest() + "): the driver options that take the")
    print("// next arguments as their values. BENNETT_SEPARATE(spelling, match, values): `Exact`, the argument is the")
    print("// spelling; `Prefix`, it starts with it (JoinedAndSeparate). `values` arguments follow it.")
    for spelling, (match, count) in sorted(found.items()):
        print(f'BENNETT_SEPARATE("{spelling}", {match}, {count})')


if __name__ == "__main__":
    main(sys.argv[1])
