//! Cumulative compile work. Circuit rewinds release scratch but retain their work.

use std::cell::{Cell, RefCell};

/// Work accumulated during one applied-function compilation.
/// Each counter has its own unit. These counts do not limit the device clock.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct WorkCounts {
    /// Possible-return answers consumed by called contexts.
    pub summary_lookups: usize,
    /// Abstract block visits begun by the worklist.
    pub block_visits: usize,
    /// Reached block transfers evaluated by the worklist.
    pub transfers: usize,
    /// Memoized specialized call context probes, including misses.
    pub call_lookups: usize,
    /// Instructions inspected by the planning and shape fault scans.
    pub fault_scans: usize,
    /// Gates built or copied, including discarded circuits and inverse gates.
    pub gates_generated: usize,
    /// Generated gates in operand proofs, traces and exit replay.
    pub temporary_gates: usize,
    /// Gates removed from circuits at a checkpoint.
    pub gates_rewound: usize,
    /// Forward gates inspected by address replay.
    pub replay_gates: usize,
    /// Address assignment packs updated at gate targets.
    pub target_packs: usize,
    /// Address assignment packs processed at gate controls.
    pub control_packs: usize,
    /// Address candidates tested in a known-bit interval.
    pub interval_addresses: usize,
    /// Device-step attempts evaluated by the small-input trace proof.
    pub trace_attempts: usize,
    /// Gate visits during complete circuit comparisons.
    pub comparison_gates: usize,
    /// Bits materialized or copied by operand readers.
    pub operand_bits: usize,
    /// Data segment entries inspected when checking an address.
    pub declaration_checks: usize,
    /// Assignment packs retrieved for address and guard bits.
    pub pack_reads: usize,
    /// Address bits reconstructed and assignment packs tested during replay.
    pub address_bits: usize,
    /// Gates in the chosen circuit, including its inverse.
    pub final_gates: usize,
    /// Instructions and terminators evaluated by proofs and lowering.
    pub operations: usize,
    /// Reached edges or call targets examined or activated.
    pub successors: usize,
    /// Switch case and indirect address tests, including coverage checks.
    pub target_checks: usize,
    /// Suspended called contexts woken by a possible normal return.
    pub dependencies: usize,
    /// Fact elements and table entries written.
    pub fact_stores: usize,
    /// Fact elements compared and joined.
    pub fact_joins: usize,
    /// Fact elements read during projection and control.
    pub fact_reads: usize,
    /// Call key elements fed to the hash.
    pub key_hash_words: usize,
    /// Call key elements compared in cache equality.
    pub key_compare_words: usize,
    /// Completed specialized call contexts stored for reuse.
    pub cache_writes: usize,
    /// Return word elements translated to the caller's identities.
    pub cache_result_words: usize,
    /// In-bounds candidate addresses inspected for access.
    pub memory_candidates: usize,
    /// Requested bytes over all inspected candidate starts.
    pub candidate_bytes: usize,
    /// Individual byte reads and queued byte writes.
    pub memory_bytes: usize,
    /// Loaded bits materialized and inspected for selection.
    pub memory_bits: usize,
    /// Bits examined by the literal extractor.
    pub definite_bits: usize,
    /// Bits of successfully resolved literal call targets.
    pub literal_target_bits: usize,
    /// Slot, bit and memory elements copied into proof snapshots.
    pub snapshot_words: usize,
    /// Point and block visits during loop-shape and copy-path inspection.
    pub shape_visits: usize,
    /// Guard and address replay queries attempted.
    pub address_queries: usize,
    /// Program and fact table entries inspected.
    pub table_entries: usize,
    /// Selector bits and shared-source relationships inspected.
    pub selector_bits: usize,
    /// Targets and controls mapped to their final wire positions.
    pub placement_wires: usize,
    /// Stored outgoing graph edges inspected by shape proofs.
    pub flow_edges: usize,
    /// Conditional value tests when querying possible successors.
    pub branch_tests: usize,
    /// Bits inspected to bound an address before interval enumeration.
    pub address_bound_bits: usize,
    /// Uncached call proofs scheduled to resume a caller.
    pub context_schedules: usize,
    /// Gates generated by speculative modular exit replay.
    pub exit_replay_gates: usize,
    /// Frame slots saved for modular entry and exit replay.
    pub snapshot_slots: usize,
    /// Recorded modular candidates examined for eligibility.
    pub modular_attempts: usize,
    /// Generated suffix gates moved into the selected circuit.
    pub moved_gates: usize,
    /// Result and fault bits examined for the output XOR.
    pub result_bits: usize,
    /// Instructions and terminators inspected for structural validation.
    pub structural_cells: usize,
    /// Completed independent call contexts stored by function.
    pub summary_table_writes: usize,
    /// Function-indexed context reads for independent arguments.
    pub summary_table_reads: usize,
    /// Argument bits inspected to classify a call context.
    pub context_bits: usize,
    /// Successors retained for later control-flow proofs.
    pub flow_edge_stores: usize,
    /// Abstract blocks placed on the worklist after an edge or fact change.
    pub block_schedules: usize,
}

pub(super) enum Work {
    SummaryLookups,
    BlockVisits,
    Transfers,
    CallLookups,
    FaultScans,
    GatesGenerated,
    TemporaryGates,
    GatesRewound,
    ReplayGates,
    TargetPacks,
    ControlPacks,
    IntervalAddresses,
    TraceAttempts,
    ComparisonGates,
    OperandBits,
    DeclarationChecks,
    PackReads,
    AddressBits,
    FinalGates,
    Operations,
    Successors,
    TargetChecks,
    Dependencies,
    FactStores,
    FactJoins,
    FactReads,
    KeyHashWords,
    KeyCompareWords,
    CacheWrites,
    CacheResultWords,
    MemoryCandidates,
    CandidateBytes,
    MemoryBytes,
    MemoryBits,
    DefiniteBits,
    LiteralTargetBits,
    SnapshotWords,
    ShapeVisits,
    AddressQueries,
    TableEntries,
    SelectorBits,
    PlacementWires,
    FlowEdges,
    BranchTests,
    AddressBoundBits,
    ContextSchedules,
    ExitReplayGates,
    SnapshotSlots,
    ModularAttempts,
    MovedGates,
    ResultBits,
    StructuralCells,
    SummaryTableWrites,
    SummaryTableReads,
    ContextBits,
    FlowEdgeStores,
    BlockSchedules,
}

thread_local! {
    static CURRENT: RefCell<Option<WorkCounts>> = const { RefCell::new(None) };
    static PHASE: Cell<Phase> = const { Cell::new(Phase::Emission) };
}

pub(super) fn add(kind: Work, count: usize) {
    CURRENT.with_borrow_mut(|current| {
        if let Some(current) = current {
            let units = match kind {
                Work::SummaryLookups => &mut current.summary_lookups,
                Work::BlockVisits => &mut current.block_visits,
                Work::Transfers => &mut current.transfers,
                Work::CallLookups => &mut current.call_lookups,
                Work::FaultScans => &mut current.fault_scans,
                Work::GatesGenerated => &mut current.gates_generated,
                Work::TemporaryGates => &mut current.temporary_gates,
                Work::GatesRewound => &mut current.gates_rewound,
                Work::ReplayGates => &mut current.replay_gates,
                Work::TargetPacks => &mut current.target_packs,
                Work::ControlPacks => &mut current.control_packs,
                Work::IntervalAddresses => &mut current.interval_addresses,
                Work::TraceAttempts => &mut current.trace_attempts,
                Work::ComparisonGates => &mut current.comparison_gates,
                Work::OperandBits => &mut current.operand_bits,
                Work::DeclarationChecks => &mut current.declaration_checks,
                Work::PackReads => &mut current.pack_reads,
                Work::AddressBits => &mut current.address_bits,
                Work::FinalGates => &mut current.final_gates,
                Work::Operations => &mut current.operations,
                Work::Successors => &mut current.successors,
                Work::TargetChecks => &mut current.target_checks,
                Work::Dependencies => &mut current.dependencies,
                Work::FactStores => &mut current.fact_stores,
                Work::FactJoins => &mut current.fact_joins,
                Work::FactReads => &mut current.fact_reads,
                Work::KeyHashWords => &mut current.key_hash_words,
                Work::KeyCompareWords => &mut current.key_compare_words,
                Work::CacheWrites => &mut current.cache_writes,
                Work::CacheResultWords => &mut current.cache_result_words,
                Work::MemoryCandidates => &mut current.memory_candidates,
                Work::CandidateBytes => &mut current.candidate_bytes,
                Work::MemoryBytes => &mut current.memory_bytes,
                Work::MemoryBits => &mut current.memory_bits,
                Work::DefiniteBits => &mut current.definite_bits,
                Work::LiteralTargetBits => &mut current.literal_target_bits,
                Work::SnapshotWords => &mut current.snapshot_words,
                Work::ShapeVisits => &mut current.shape_visits,
                Work::AddressQueries => &mut current.address_queries,
                Work::TableEntries => &mut current.table_entries,
                Work::SelectorBits => &mut current.selector_bits,
                Work::PlacementWires => &mut current.placement_wires,
                Work::FlowEdges => &mut current.flow_edges,
                Work::BranchTests => &mut current.branch_tests,
                Work::AddressBoundBits => &mut current.address_bound_bits,
                Work::ContextSchedules => &mut current.context_schedules,
                Work::ExitReplayGates => &mut current.exit_replay_gates,
                Work::SnapshotSlots => &mut current.snapshot_slots,
                Work::ModularAttempts => &mut current.modular_attempts,
                Work::MovedGates => &mut current.moved_gates,
                Work::ResultBits => &mut current.result_bits,
                Work::StructuralCells => &mut current.structural_cells,
                Work::SummaryTableWrites => &mut current.summary_table_writes,
                Work::SummaryTableReads => &mut current.summary_table_reads,
                Work::ContextBits => &mut current.context_bits,
                Work::FlowEdgeStores => &mut current.flow_edge_stores,
                Work::BlockSchedules => &mut current.block_schedules,
            };
            *units = units.saturating_add(count);
        }
    });
}

pub(super) struct Scope(Option<WorkCounts>);

impl Scope {
    pub(super) fn start() -> Self {
        Self(CURRENT.replace(Some(WorkCounts::default())))
    }

    pub(super) fn counts(&self) -> WorkCounts {
        CURRENT.with_borrow(|counts| counts.expect("active compile work meter"))
    }
}

impl Drop for Scope {
    fn drop(&mut self) {
        CURRENT.set(self.0);
    }
}

#[derive(Clone, Copy)]
enum Phase {
    Emission,
    Proof,
    Exit,
}

pub(super) struct Temporary(Phase);

impl Temporary {
    pub(super) fn start() -> Self {
        Self(PHASE.replace(Phase::Proof))
    }

    pub(super) fn exit() -> Self {
        Self(PHASE.replace(Phase::Exit))
    }
}

impl Drop for Temporary {
    fn drop(&mut self) {
        PHASE.set(self.0);
    }
}

pub(super) fn gate() {
    add(Work::GatesGenerated, 1);
    match PHASE.get() {
        Phase::Emission => {}
        Phase::Proof => add(Work::TemporaryGates, 1),
        Phase::Exit => {
            add(Work::TemporaryGates, 1);
            add(Work::ExitReplayGates, 1);
        }
    }
}
