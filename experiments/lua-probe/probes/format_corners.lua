-- string.format corner cases: flags, widths, precision, rounding halves, special values, %q and %a.
local f = string.format
print(f("[%5d][%-5d][%05d][%+d][% d][%+.3d]", 42, 42, 42, 42, 42, 7))
print(f("[%x][%X][%#x][%#o][%o][%x]", 255, 255, 255, 8, 8, -1))
print(f("[%.0f][%.0f][%.0f][%.0f][%.1f][%.2f]", 0.5, 1.5, 2.5, -0.5, 0.05, 2.675))
print(f("[%g][%g][%g][%g][%g][%g]", 1e20, 1e-5, 100000, 1e15, 0.0001, 123456789))
print(f("[%.3g][%#.3g][%.0e][%#.0e][%10.3e][%-10.2e]", 1.0, 1.0, 12345.0, 3.0, -1.5e-7, 6.02e23))
print(f("[%.14g][%.17g][%.20f]", math.pi, 0.1, 1 / 3))
print(f("[%5.1f][%f][%e][%g]", -0.0, -0.0, 0.0, -0.0))
print(f("[%f][%f][%e][%g][%.3f]", 1 / 0, -1 / 0, 1 / 0, -1 / 0, 1e300 * 1e10))
-- Subnormals under %a are spelled differently by musl and glibc (front/tests/tests/printf_hex_float.rs).
print(f("[%a][%a][%a][%A][%.3a][%a]", 1.0, 0.1, -2.5, 255.5, 1 / 3, 2 ^ -1022))
print(f("[%a][%a][%a]", 2 ^ 1023, -0.0, math.huge))
print(f("[%5.2s][%-6s][%.0s][%s][%s]", "abcdef", "ab", "gone", true, nil))
print(f("[%c%c%c][%i][%u]", 76, 117, 97, -3, 3))
print(f("%q", "tab\tnewline\nnul\0quote\"backslash\\bell\a\200\255end"))
print(f("%q %q %q %q", math.mininteger, math.maxinteger, 1 / 0, -1 / 0))
print(f("%q %q %q", 0.1, -0.0, 2 ^ 63))
print(f("[%99.98f]", 1 / 7):len(), f("%.99f", 1 / 3):sub(1, 12))
print(pcall(f, "%d", 3.5))
print(pcall(f, "%10.100f", 1))
print(pcall(f, "%z", 1))
print(f("%s|%s|%s|%s", 1e15, 1e16, 2 ^ 53, -2 ^ 63))
print(f("%s|%s|%s|%s|%s", 3.0, -0.0, 1e100, 123456789012, 0.1 + 0.2))
print(tostring(2 ^ 63), tostring(-(2 ^ 63)), math.tointeger(2 ^ 53), math.tointeger(2 ^ 63))
