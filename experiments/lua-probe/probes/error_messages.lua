-- Error messages and values as the interpreter forms them, with positions inside the chunk.
local function try(f, ...) print(select(2, pcall(f, ...))) end
try(function() local t = {} return t.x.y end)
try(function() return undefined_global() end)
try(function() local s = "abc" return s + 1 end)
try(function() local t = {} return #nil end)
try(function() return {} < {} end)
try(function() return 1 < "2" end)
try(function() local a; a.b = 1 end)
print(select(2, pcall(error, {code = 7})).code)
try(function() error("level one") end)
try(function() error("level two", 2) end)
try(function() error("no position", 0) end)
try(function() error() end)
try(function() error(nil) end)
try(function() error(42) end)
try(string.rep, "x", -1)
try(string.rep, "x", 1 << 62)
try(function() return ("x"):bad() end)
try(setmetatable, 1, {})
try(function() return math.floor("a") end)
try(function() return string.sub() end)
try(function() return ipairs() end)
try(tostring)
try(function() local t = setmetatable({}, {__index = function(t, k) error("no field " .. k) end}) return t.f end)
try(function() local t = setmetatable({}, {__newindex = function() error("frozen", 2) end}) t.x = 1 end)
try(load("return 1 +"))
print(load("return 1 +"))
print(load("x ="))
print(load("return 'unfinished"))
print(load("goto nowhere"))
print(load("local x <const> = 1; x = 2"))
print(load("break"))
print(load(string.rep("(", 300) .. "1" .. string.rep(")", 300)))
local co = coroutine.create(function() error("in coroutine") end)
print(coroutine.resume(co))
print(coroutine.status(co), coroutine.resume(co))
print(coroutine.resume(coroutine.running()))
print(pcall(coroutine.yield))
print(xpcall(function() local x = nil; return x.y end, function(m) return "traced: " .. m end))
print(select("#", pcall(error)))
local ok, msg = pcall(function() local function f(n) return n == 0 and error("bottom") or f(n - 1) end return f(150) end)
print(ok, msg)
