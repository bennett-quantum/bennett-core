-- Integer and float division, modulo, overflow and conversion, as Lua 5.4 defines them.
local maxi, mini = math.maxinteger, math.mininteger
print(7 // 2, -7 // 2, 7 // -2, -7 // -2, 7 % 3, -7 % 3, 7 % -3, -7 % -3)
print(7.0 // 2, -7.5 // 2, 7 // 0.0, -7 // 0.0, 0 / 0 ~= 0 / 0, 5.3 % -2, -5.3 % 2)
print(mini // -1, mini % -1, mini * -1, maxi + 1 == mini, maxi * 2, mini - 1 == maxi)
print(math.fmod(-7, 2), math.fmod(7, -2), math.fmod(mini, -1), math.fmod(-7.5, 2), math.fmod(1, 0.0))
print(pcall(function() return 1 // 0 end))
print(pcall(function() return 1 % 0 end))
print(pcall(math.fmod, 1, 0))
print(1 / 0, -1 / 0, 2 ^ 1024, math.abs(mini), -mini, math.ult(1, -1), math.ult(-1, 1))
print(3 / 2, 4 / 2, 2 ^ 2, 1e308 + 1e308, -(0 / 0) ~= -(0 / 0))
print(maxi + 0.0, mini + 0.0, maxi + 0.0 == 2 ^ 63, maxi // 1 | 0, 2 ^ 53 + 1)
print(math.tointeger(3.0), math.tointeger(3.5), math.tointeger("8"), math.tointeger(-0.0), math.tointeger(2 ^ 62))
print("10" + 1, "0x10" + 0, "1e2" + 0, " 7 " * 2, "9223372036854775807" + 0, "9223372036854775808" + 0)
print(10 == "10", 0x7fffffffffffffff, 0xffffffffffffffff, 0x10000000000000000, 1e2 == 100)
print(math.floor(-0.5), math.ceil(-0.5), math.floor(2 ^ 62 + 0.0), math.floor(1e100), math.ceil(-1e100))
print(5 >> 1, -1 >> 1, 1 << 63, 1 << 64, -1 << 1, 3 & 5, 3 | 5, 3 ~ 5, ~0, 2 ^ 63 == 1 << 63)
print(pcall(function() return 1.5 | 0 end))
print(pcall(function() return "a" + 1 end))
print(maxi < 2 ^ 63, maxi + 1.0 == 2 ^ 63, mini == -2 ^ 63, maxi == 2 ^ 63, 2 ^ 63 > maxi)
print(string.format("%.17g %.17g", 0.1 * 3, 1 - 0.9), 1e-310 > 0, 2 ^ -1075 == 0, 5e-324 / 2)
print(tostring(1e15), tostring(1e16), tostring(-1e-5), tostring(123.0), 7 // 7.0, 0.0 == -0.0, 1 / -0.0)
print(math.type(1), math.type(1.0), math.type("1"), math.max(1, 2.5, -1), math.min(mini, -1 / 0))
